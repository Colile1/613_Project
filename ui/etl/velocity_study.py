# velocity_study.py : reproducible evidence for the velocity-rule decision
# Runs each candidate configuration on the local pipeline with three random
# seeds and measures, for the rule as it would be written in asa/query.sql:
#   noise     - share of normal payments that raise a VELOCITY alert
#   detection - share of simulated card-testing attacks that raise one
# Writes docs/decisions/velocity_study_results.md.
# Run from the project root:  python -m ui.etl.velocity_study

import tempfile
from datetime import datetime, timezone
from pathlib import Path
from statistics import mean

from ui.etl import generator, threshold, transform
from ui.etl.session import PipelineSession
from ui.storage.db import Database

OUT = Path(__file__).resolve().parents[2] / "docs" / "decisions" / "velocity_study_results.md"
SEEDS = [11, 42, 99]
START = datetime(2026, 1, 1, tzinfo=timezone.utc)
ALL_CARDS = list(generator.CARDS)

# (option, label, cards, events/s, simulated seconds, window s, threshold)
SCENARIOS = [
    ("1", "Keep as is", 50, 10.0, 1200, 300, 5),
    ("2", "Lower rate, 1-min window", 50, 1.0, 3600, 60, 8),
    ("3", "5-second window", 50, 10.0, 1200, 5, 10),
    ("4", "5 000 cards, rule unchanged (chosen)", 5000, 10.0, 1200, 300, 5),
    ("4b", "1 000 cards, rule unchanged", 1000, 10.0, 1200, 300, 5),
]


# Runs one configuration and returns the rule's score plus traffic facts.
def run(cards, rate, seconds, window_s, rule, seed, folder):
    generator.CARDS[:] = ALL_CARDS[:cards]
    db = Database(Path(folder) / f"study-{cards}-{rate}-{seed}.db")
    try:
        s = PipelineSession(db)
        s.update("config", {"rate": rate})
        s.reset(seed)
        s.clock = START   # fixed start: window boundaries line up the same way every run
        s.advance(seconds)
        events, _ = s.result()
        valid = [e for e in events if transform.is_valid(e)]
        counts = threshold.window_counts(valid, window_s)
        normal = sorted(c for c, a in counts if a is None)
        result = threshold.score(counts, rule)
        result.update(events=len(events), median=normal[len(normal) // 2] if normal else 0)
        return result
    finally:
        db.close()
        generator.CARDS[:] = ALL_CARDS


# Pure function: averages the per-seed results of one scenario.
def summarise(scenario, runs):
    option, label, cards, rate, seconds, window_s, rule = scenario
    return {"option": option, "label": label, "cards": cards, "rate": rate, "window_s": window_s, "rule": rule,
            "noise": mean(r["normal_alert_rate"] for r in runs), "detection": mean(r["attack_detection"] for r in runs),
            "detection_min": min(r["attack_detection"] for r in runs), "detection_max": max(r["attack_detection"] for r in runs),
            "attacks": sum(r["attacks"] for r in runs), "median": mean(r["median"] for r in runs),
            "events": sum(r["events"] for r in runs)}


# Pure function: the results table as Markdown.
def to_markdown(rows):
    lines = ["# Velocity rule study - results", "",
             "Generated by `python -m ui.etl.velocity_study` (seeds " + ", ".join(map(str, SEEDS)) + "). "
             "Noise = share of normal payments that alert; detection = share of simulated card-testing attacks "
             "(one card, 8-15 payments within a second) that alert. Payments made while an attack is still inside "
             "the window are excluded from noise.", "",
             "| Option | Configuration | Cards | Events/s | Rule | Median count per window | Noise | Attacks detected (min-max) | Attacks | Events |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['option']} | {r['label']} | {r['cards']:,} | {r['rate']:g} | COUNT(*) > {r['rule']} in {r['window_s']} s | "
                     f"{r['median']:.1f} | {r['noise'] * 100:.2f}% | {r['detection'] * 100:.0f}% ({r['detection_min'] * 100:.0f}-{r['detection_max'] * 100:.0f}%) | "
                     f"{r['attacks']} | {r['events']:,} |")
    return "\n".join(lines) + "\n"


# Output logic: prints and writes the table.
def display_results(markdown):
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(markdown, encoding="utf-8")
    print(markdown)
    print("Written:", OUT)


def main():
    rows = []
    with tempfile.TemporaryDirectory() as folder:
        for scenario in SCENARIOS:
            _, _, cards, rate, seconds, window_s, rule = scenario
            rows.append(summarise(scenario, [run(cards, rate, seconds, window_s, rule, seed, folder) for seed in SEEDS]))
    display_results(to_markdown(rows))


if __name__ == "__main__":
    main()