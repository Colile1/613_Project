# amount_study.py : reproducible evidence for the amount-anomaly rule (query 5)
# Compares three forms of "amount > 3x a 10-minute average baseline" on the
# local pipeline, for the old 50-card pool and the 5 000-card pool, over three
# seeds. Ground truth: injected fraud spikes (amount x8-x25). Also reports how
# many rows each payment is joined with - the main cost driver in Stream Analytics.
# Writes docs/decisions/amount_rule_results.md.
# Run from the project root:  python -m ui.etl.amount_study

import tempfile
from collections import deque
from datetime import timedelta
from datetime import datetime, timezone
from pathlib import Path

from ui.etl import alerts, generator, transform
from ui.etl.session import PipelineSession
from ui.storage.db import Database

OUT = Path(__file__).resolve().parents[2] / "docs" / "decisions" / "amount_rule_results.md"
SEEDS = [11, 42, 99]
START = datetime(2026, 1, 1, tzinfo=timezone.utc)
ALL_CARDS = list(generator.CARDS)


# Pure function: average rows a rolling self-join compares each payment with.
def rolling_join_rows(valid, field, size=timedelta(minutes=10)):
    total, n = 0, 0
    for evs in alerts.by_card(valid, field).values():
        window = deque()
        for e in evs:
            window.append(e)
            while e["_ts"] - window[0]["_ts"] > size:
                window.popleft()
            total, n = total + len(window), n + 1
    return total / max(1, n)


# (key, label, alert function, join-rows function)
VARIANTS = [
    ("card", "Card's own rolling 10-min average (original)",
     lambda v, wm: alerts.amount_alerts(alerts.by_card(v, "card_id"), 3.0, wm), lambda v: rolling_join_rows(v, "card_id")),
    ("cat_roll", "Category rolling 10-min average, self-join",
     lambda v, wm: alerts.amount_alerts(alerts.by_card(v, "merchant_category"), 3.0, wm), lambda v: rolling_join_rows(v, "merchant_category")),
    ("cat_pre", "Category 10-min average, pre-aggregated each minute (deployed)",
     lambda v, wm: alerts.category_amount_alerts(v, 3.0, wm), lambda v: 1.0),
]


# Runs one seed; returns per variant (spikes, caught, false, normal, join rows).
def run(cards, seed, folder):
    generator.CARDS[:] = ALL_CARDS[:cards]
    db = Database(Path(folder) / f"amount-{cards}-{seed}.db")
    try:
        s = PipelineSession(db)
        s.reset(seed)
        s.clock = START   # fixed start: window boundaries line up the same way every run
        s.advance(1200)
        events, result = s.result()
        valid = [e for e in events if transform.is_valid(e)]
        spikes = {e["transaction_id"] for e in valid if e.get("_fraud_injected")}
        out = {}
        for key, _, alert_fn, join_fn in VARIANTS:
            hits = {a["transaction_id"] for a in alert_fn(valid, result["watermark"])}
            out[key] = (len(spikes), len(hits & spikes), len(hits - spikes), len(valid) - len(spikes), join_fn(valid))
        return out
    finally:
        db.close()
        generator.CARDS[:] = ALL_CARDS


# Pure function: one Markdown row per pool size and variant.
def rows_for(cards, runs):
    rows = []
    for key, label, _, _ in VARIANTS:
        spikes, caught, false, normal = (sum(r[key][i] for r in runs) for i in range(4))
        join = sum(r[key][4] for r in runs) / len(runs)
        rows.append(f"| {cards:,} | {label} | {caught} of {spikes} ({caught / max(1, spikes) * 100:.0f}%) | "
                    f"{false} ({false / max(1, normal) * 100:.2f}%) | {join:,.1f} |")
    return rows


# Pure function: the results document.
def to_markdown(table_rows):
    return "\n".join([
        "# Amount-anomaly rule study - results", "",
        "Generated by `python -m ui.etl.amount_study` (seeds " + ", ".join(map(str, SEEDS)) + "; 20 simulated minutes at "
        "10 events/s per seed). Ground truth: injected fraud spikes (one payment 8-25 times its usual size). "
        "Rule: alert when amount > 3 x the 10-minute average of the baseline. Join rows = how many rows each payment "
        "is compared with in Stream Analytics (the main cost driver).", "",
        "| Cards | Baseline | Spikes caught | False alerts (% of normal payments) | Join rows per payment |",
        "|---|---|---|---|---|", *table_rows, ""])


# Output logic: prints and writes the results.
def display_results(markdown):
    OUT.write_text(markdown, encoding="utf-8")
    print(markdown)
    print("Written:", OUT)


def main():
    table_rows = []
    with tempfile.TemporaryDirectory() as folder:
        for cards in (50, 5000):
            table_rows += rows_for(cards, [run(cards, seed, folder) for seed in SEEDS])
    display_results(to_markdown(table_rows))


if __name__ == "__main__":
    main()